const part = (id: string, kind: PartKind, a: Point, b: Point, value = 0, ic?: number): Part =>
  ic === undefined ? { id, kind, a, b, value } : { id, kind, a, b, value, ic };
const wire = (id: string, a: Point, b: Point) => part(id, 'W', a, b);

/** حلقه ساده: باتری و یک مقاومت */
const loop = (e: number, r: number): Circuit => ({
  ground: [3, 9],
  parts: [
    part('E1', 'V', [3, 3], [3, 9], e),
    part('R1', 'R', [3, 3], [8, 3], r),
    wire('W1', [8, 3], [8, 9]),
    wire('W2', [8, 9], [3, 9]),
  ],
});
/** باتری + دو مقاومت سری (R1 بالا، R2 سمت راست) */
